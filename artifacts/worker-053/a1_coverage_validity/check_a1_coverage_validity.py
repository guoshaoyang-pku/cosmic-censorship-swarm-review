def now() -> str:
    return datetime.now(CST).isoformat(timespec="seconds")


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# --------------------------------------------------------------------------- policy
def targets_in_review(d: dict) -> set:
    """Reimplementation of astra_lifecycle._targets_in_review (V3 cross-checks it)."""
    out = set()
    for key in ("target_id", "target", "target_subnode"):
        v = d.get(key)
        if isinstance(v, str):
            out.add(v)
        elif isinstance(v, dict):
            for k2 in ("target_id", "target_subnode", "subnode", "node_id"):
                if isinstance(v.get(k2), str):
                    out.add(v[k2])
    norm = set()
    for t in out:
        norm.add(TARGET_ALIASES.get(t, TARGET_ALIASES.get(t.upper(), t)))
    return norm


def raw_targets(d: dict) -> list:
    out = []
    for key in ("target_id", "target", "target_subnode"):
        v = d.get(key)
        if isinstance(v, str):
            out.append(v)
        elif isinstance(v, dict):
            for k2 in ("target_id", "target_subnode", "subnode", "node_id"):
                if isinstance(v.get(k2), str):
                    out.append(v[k2])
    return out


def explicit_pins(d: dict) -> list:
    """Reimplementation of astra_lifecycle._explicit_pins."""
    pins = []
    for key in PIN_KEYS:
        v = d.get(key)
        if isinstance(v, str):
            pins.append(v.lower())
    for key in ("target", "artifact"):
        v = d.get(key)
        if isinstance(v, dict):
            for k2 in ("sha256", "artifact_sha256", "reviewed_sha256"):
                if isinstance(v.get(k2), str):
                    pins.append(v[k2].lower())
    return pins


def pin_matches(pin: str, h: str) -> bool:
    """Reimplementation of the scan's prefix predicate."""
    return bool(pin) and bool(h) and (pin.startswith(h[:12]) or h.startswith(pin[:12]))


def scan(hashes: dict, reviews_dir: Path) -> dict:
    """Independent scan. Returns per-target entries with timestamps for V4."""
    cov = {t: [] for t in hashes}
    for rp in sorted(reviews_dir.glob("*.json")):
        try:
            d = json.loads(rp.read_text())
        except Exception:
            continue
        if not isinstance(d, dict):
            continue
        v = str(d.get("verdict", "")).lower()
        if v not in VERDICT_KINDS:
            continue
        reviewer = str(d.get("reviewer") or d.get("actor") or "?")
        full = d.get("counts_as_full_schema_verdict") is not False
        pins = explicit_pins(d)
        for t in targets_in_review(d):
            if t not in cov:
                continue
            h = hashes.get(t, {}).get("sha256") or ""
            if any(pin_matches(p, h) for p in pins):
                cov[t].append({
                    "file": rp.name, "reviewer": reviewer, "verdict": v,
                    "counts_as_full_schema_verdict": full,
                    "created_at": str(d.get("created_at") or ""),
                    "mtime": datetime.fromtimestamp(rp.stat().st_mtime, CST).isoformat(timespec="seconds"),
                })
    return cov


def distinct_accepts(entries: list) -> list:
    return sorted({e["reviewer"] for e in entries
                   if e["verdict"] == "accept" and e["counts_as_full_schema_verdict"]})


def corrected_accepts(entries: list) -> tuple:
    """Reviewer's latest bound verdict at this target+hash wins (self-amendment)."""
    by_rev = {}
    for e in entries:
        by_rev.setdefault(e["reviewer"], []).append(e)
    conflicted, corrected, superseded_accepts = [], [], []
    for rev, es in sorted(by_rev.items()):
        if len(es) < 2:
            if es[0]["verdict"] == "accept" and es[0]["counts_as_full_schema_verdict"]:
                corrected.append(rev)
            continue
        if len({e["verdict"] for e in es}) > 1:
            ordered = sorted(es, key=lambda e: (e["created_at"] or "", e["file"]))
            latest = ordered[-1]
            conflicted.append({
                "reviewer": rev,
                "verdicts": [{"file": e["file"], "verdict": e["verdict"],
                              "created_at": e["created_at"]} for e in ordered],
                "authoritative_file": latest["file"],
                "authoritative_verdict": latest["verdict"],
            })
            if latest["verdict"] == "accept" and latest["counts_as_full_schema_verdict"]:
                corrected.append(rev)
            for e in ordered[:-1]:
                if e["verdict"] == "accept":
                    superseded_accepts.append({"reviewer": rev, "file": e["file"],
                                               "superseded_by": latest["file"]})
    return sorted(corrected), conflicted, superseded_accepts


def path_form_targets(hashes: dict, reviews_dir: Path) -> list:
    """Reviews whose target names a canonical artifact path -> dropped by normalisation."""
    art_to_node = {v["artifact"]: t for t, v in hashes.items()}
    found = []
    for rp in sorted(reviews_dir.glob("*.json")):
        try:
            d = json.loads(rp.read_text())
        except Exception:
            continue
        if not isinstance(d, dict):
            continue
        v = str(d.get("verdict", "")).lower()
        if v not in VERDICT_KINDS:
            continue
        norm = targets_in_review(d)
        dropped = sorted(t for t in norm if t not in hashes)
        if not dropped:
            continue
        for raw in raw_targets(d):
            base = raw.split("#", 1)[0].lstrip("./")
            if base not in art_to_node:
                continue
            node = art_to_node[base]
            cur = hashes[node]["sha256"]
            pins = explicit_pins(d)
            reaches_current = any(pin_matches(p, cur) for p in pins)
            found.append({
                "file": rp.name, "raw_target": raw, "verdict": v,
                "score": d.get("score"), "would_bind_node": node,
                "pin_reaches_current_hash": reaches_current,
                "counts_as_full_schema_verdict": d.get("counts_as_full_schema_verdict") is not False,
            })
    return found


