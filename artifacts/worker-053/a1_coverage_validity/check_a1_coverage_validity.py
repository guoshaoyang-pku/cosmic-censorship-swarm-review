"""W053-A1-COVERAGE-VALIDITY-01 -- independent validity census of the A1 review-coverage scan.

Question this answers, at one pinned snapshot:
  Does `astra_lifecycle.review_coverage` -- the authoritative instrument behind the
  G-F0 / G-FORM / G-AUDIT "distinct accept reviewer(s)" counts -- report a census
  that survives (a) same-reviewer self-amendment at one target+hash and
  (b) path-form target ids for canonical artifacts?

Method: deterministic, read-only, stdlib-only.
  V1  pin every canonical artifact by hashing it in-run (single-read), plus the
      module file that defines the scan policy.
  V2  import `astra_lifecycle` and call its `review_coverage` -- authoritative output.
  V3  independently reimplement the documented policy and require exact agreement
      with V2 on the (file, reviewer, verdict, full) entry set per target.
  V4  detect reviewers holding more than one bound verdict of differing kind on the
      SAME target at the SAME hash; order by (created_at, filename) and derive the
      corrected accept-reviewer set.
  V5  tabulate raw vs corrected distinct-accept counts.
  V6  detect reviews whose target is a canonical artifact PATH (optionally with a
      '#fragment'/'#sha256:' suffix): these are never normalised to a node id, so
      they are invisible to V2 no matter what hash they pin. Classify each by
      whether its explicit pin reaches the current canonical hash.
  V7  confirm scoped verdicts (counts_as_full_schema_verdict=false) are excluded.
  V8  compare V2 against the recorded controller_gate_audit counts, and state the
      structural limit: the recorded reason is generated by the same scan, so it
      reproduces V2's blind spots rather than detecting them.

Controls K1..K8 are planted defects exercised through the SAME predicate functions
used in V3-V7, in a sandbox corpus; they are not a test of `astra_lifecycle`.

Authority: this is a measurement report. It sets no gate verdict, no node status,
and no validation_status. Worker verdicts are advisory evidence only.

Usage:  python3 check_a1_coverage_validity.py [--out DIR]
"""
