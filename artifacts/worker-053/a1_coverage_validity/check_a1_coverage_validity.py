def import_authoritative():
    try:
        sys.path.insert(0, str(ROOT / "research_map"))
        import astra_lifecycle as al  # noqa: E402
        # constants must not silently diverge from this file's copies
        assert tuple(al.VERDICT_KINDS) == tuple(VERDICT_KINDS), "VERDICT_KINDS drift"
        assert dict(al.TARGET_ALIASES) == dict(TARGET_ALIASES), "TARGET_ALIASES drift"
        return al
    except Exception:
        return None


